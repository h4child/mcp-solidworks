"""
Packaging and documentation drift checks (v5.22.0).

Two kinds of drift reached a release before these existed:

* The README, .claude/CLAUDE.md and tests/README.md all said 158 (or 150)
  tools for several commits after the server had 167 -- the version test only
  checked that the README *mentions* the version, not what it claims.
* chatgpt-solidworks-mcp-plugin/ was a hand-maintained copy of the whole
  server that stopped at 5.21.0 and kept shipping already-fixed bugs. The
  plugin is now generated by scripts/build_chatgpt_plugin.py; these tests
  prove the generator still produces a complete, correctly versioned plugin.
"""

import json
import os
import re
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))

pytest.importorskip("win32com.client",
                    reason="the server module needs pywin32 (Windows only)")

import server  # noqa: E402
import build_chatgpt_plugin  # noqa: E402

TOOLS = server.mcp._tool_manager._tools
UNCONDITIONAL = len(set(TOOLS) - {"execute_python"})


def _read(relative_path: str) -> str:
    with open(os.path.join(ROOT, relative_path), encoding="utf-8") as handle:
        return handle.read()


@pytest.mark.parametrize("relative_path, pattern", [
    ("README.md", r"\*\*(\d+) ferramentas incondicionais"),
    ("README.md", r"Este servidor registra (\d+) ferramentas incondicionais"),
    (".claude/CLAUDE.md", r"resolva pelas (\d+) ferramentas normais"),
    ("tests/README.md", r"as (\d+) ferramentas MCP"),
])
def test_the_documented_tool_count_matches_the_server(relative_path, pattern):
    match = re.search(pattern, _read(relative_path))
    assert match, f"{relative_path} no longer states the tool count as {pattern!r}"
    assert int(match.group(1)) == UNCONDITIONAL, (
        f"{relative_path} says {match.group(1)} tools; the server registers "
        f"{UNCONDITIONAL} unconditional tools (+ execute_python when enabled). "
        f"Update the document in the same commit that adds or removes a tool."
    )


def test_the_changelog_has_an_entry_for_the_current_version():
    version = json.loads(_read("manifest.json"))["version"]
    assert f"## [{version}]" in _read("CHANGELOG.md"), (
        f"CHANGELOG.md has no '## [{version}]' entry for the version in manifest.json"
    )


def test_the_hand_maintained_plugin_copy_is_gone():
    assert not os.path.exists(os.path.join(ROOT, "chatgpt-solidworks-mcp-plugin")), (
        "the ChatGPT plugin is generated by scripts/build_chatgpt_plugin.py; a "
        "checked-in copy of server.py drifts (it did, by ~900 lines)"
    )


def test_the_plugin_build_is_complete_and_versioned(tmp_path):
    out_dir = tmp_path / "chatgpt-plugin"
    version = build_chatgpt_plugin.build(str(out_dir))

    assert f'version = "{version}"' in _read("pyproject.toml")
    for name in build_chatgpt_plugin.RUNTIME_FILES + ("plugin.json", "mcp.json"):
        assert (out_dir / name).is_file(), f"plugin build is missing {name}"
    knowledge = out_dir / ".claude" / "knowledge"
    expected = sorted(os.listdir(os.path.join(ROOT, ".claude", "knowledge")))
    assert sorted(p.name for p in knowledge.iterdir()) == expected
    assert not (out_dir / ".claude" / "settings.local.json").exists()

    plugin = json.loads((out_dir / "plugin.json").read_text(encoding="utf-8"))
    assert plugin["version"] == version
    assert (out_dir / "server.py").read_bytes() == open(
        os.path.join(ROOT, "server.py"), "rb").read()


def test_the_plugin_zip_contains_the_build(tmp_path):
    out_dir = tmp_path / "chatgpt-plugin"
    version = build_chatgpt_plugin.build(str(out_dir))
    zip_path = build_chatgpt_plugin.make_zip(str(out_dir), version)
    import zipfile
    with zipfile.ZipFile(zip_path) as archive:
        names = set(archive.namelist())
    assert {"server.py", "plugin.json", "mcp.json"} <= names
    assert os.path.basename(zip_path) == f"solidworks-mcp-chatgpt-plugin-{version}.zip"


def test_the_catalog_measurement_script_runs():
    result = subprocess.run(
        [sys.executable, os.path.join(ROOT, "scripts", "measure_catalog.py"), "--top", "3"],
        capture_output=True, text=True, timeout=120, cwd=ROOT,
    )
    assert result.returncode == 0, result.stderr
    match = re.search(r"tools: (\d+)", result.stdout)
    assert match and int(match.group(1)) == len(TOOLS)
